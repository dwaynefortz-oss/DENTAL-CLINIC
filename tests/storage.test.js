import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, existsSync, unlinkSync, rmdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { hashPassword } from '../server/auth.js';
import sharp from 'sharp';
test('Legacy SQLite records migrate and dentist bookings and sessions persist across a restart',async()=>{
  const directory=mkdtempSync(path.join(tmpdir(),'pearl-dental-test-')),database=path.join(directory,'clinic.sqlite');
  const legacy=new DatabaseSync(database);
  legacy.exec(`CREATE TABLE users (id INTEGER PRIMARY KEY,name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,phone TEXT DEFAULT '',password TEXT NOT NULL,role TEXT NOT NULL DEFAULT 'patient');
    CREATE TABLE services (id INTEGER PRIMARY KEY,name TEXT,duration INTEGER,price INTEGER,description TEXT);
    CREATE TABLE appointments (id INTEGER PRIMARY KEY,patient_id INTEGER REFERENCES users(id),service_id INTEGER REFERENCES services(id),date TEXT,time TEXT,status TEXT DEFAULT 'Pending',notes TEXT DEFAULT '',request TEXT DEFAULT '',requested_date TEXT DEFAULT '',requested_time TEXT DEFAULT '');
    CREATE UNIQUE INDEX occupied_slot ON appointments(date,time) WHERE status IN ('Pending','Approved');
    INSERT INTO services VALUES (1,'Legacy cleaning',30,1200,'Original service');`);
  legacy.prepare('INSERT INTO users VALUES (?,?,?,?,?,?)').run(2,'Alex Morgan','alex@pearldental.test','0917 555 0124',hashPassword('PearlPatient123!'),'patient');
  legacy.prepare('INSERT INTO users VALUES (?,?,?,?,?,?)').run(1,'Legacy Admin','legacy-admin@example.test','',hashPassword('LegacyAdmin123!'),'admin');
  legacy.exec("INSERT INTO appointments(patient_id,service_id,date,time,status) VALUES (2,1,'2026-01-01','09:00','Completed')");
  legacy.close();
  let child;
  const start=()=>new Promise((resolve,reject)=>{
    child=spawn(process.execPath,['server/server.js'],{env:{...process.env,NODE_ENV:'development',PORT:'0',DB_PATH:database},stdio:['ignore','pipe','pipe']});
    child.stdout.on('data',d=>{const match=d.toString().match(/http:\/\/localhost:(\d+)/);if(match)resolve('http://127.0.0.1:'+match[1]);});
    child.on('error',reject);child.on('exit',code=>{if(code)reject(new Error('Server exited: '+code));});
  });
  const stop=()=>new Promise(resolve=>{child.once('exit',resolve);child.kill();});
  try {
    let base=await start();
    const login=await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'alex@pearldental.test',password:'PearlPatient123!'})});
    const cookie=login.headers.get('set-cookie').split(';')[0];
    let result=await fetch(base+'/api/profile',{method:'PATCH',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({name:'Persistent Patient',phone:'0917 888 7777'})});assert.equal(result.status,200);
    const photo=await sharp({create:{width:60,height:60,channels:3,background:'#2876a5'}}).png().toBuffer();
    assert.equal((await fetch(base+'/api/profile/photo',{method:'PUT',headers:{Cookie:cookie,'Content-Type':'image/png'},body:photo})).status,200);
    const photoBefore=Buffer.from(await (await fetch(base+'/api/profile/photo',{headers:{Cookie:cookie}})).arrayBuffer());
    let date=new Date();date.setDate(date.getDate()+30);if(date.getDay()===0)date.setDate(date.getDate()+1);
    const day=`${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`;
    const post=(route,body,session=cookie)=>fetch(base+'/api'+route,{method:'POST',headers:{Cookie:session,'Content-Type':'application/json'},body:JSON.stringify(body)});
    assert.equal((await post('/appointments',{service_id:1,dentist_id:1,date:day,time:'16:00'})).status,201);
    await post('/register',{name:'Second Patient',email:'second@example.test',password:'Password123!'});
    const secondLogin=await post('/login',{email:'second@example.test',password:'Password123!'});
    const secondCookie=secondLogin.headers.get('set-cookie').split(';')[0];
    assert.equal((await post('/appointments',{service_id:1,dentist_id:2,date:day,time:'16:00'},secondCookie)).status,201);
    const secondUser=(await (await fetch(base+'/api/me',{headers:{Cookie:secondCookie}})).json()).user;
    const administratorLogin=await post('/login',{email:'legacy-admin@example.test',password:'LegacyAdmin123!'});
    const administratorCookie=administratorLogin.headers.get('set-cookie').split(';')[0];
    assert.equal((await post('/accounts/'+secondUser.id+'/promote',{},administratorCookie)).status,200);
    const before=await (await fetch(base+'/api/data',{headers:{Cookie:cookie}})).json();
    assert.equal(before.appointments.find(a=>a.date==='2026-01-01').dentist_id,1);
    assert.equal(before.appointments.find(a=>a.date==='2026-01-01').service,'Legacy cleaning');
    await stop();base=await start();
    result=await fetch(base+'/api/data',{headers:{Cookie:cookie}});assert.equal(result.status,200);
    const after=await result.json();assert.equal(after.user.name,'Persistent Patient');assert.equal(after.user.phone,'0917 888 7777');assert.deepEqual(after.appointments,before.appointments);
    assert.equal(after.user.photo_url,before.user.photo_url);
    assert.deepEqual(Buffer.from(await (await fetch(base+after.user.photo_url,{headers:{Cookie:cookie}})).arrayBuffer()),photoBefore);
    assert.equal((await fetch(base+'/api/me',{headers:{Cookie:secondCookie}})).status,401);
    const promotedLogin=await post('/login',{email:'second@example.test',password:'Password123!'});
    const promotedCookie=promotedLogin.headers.get('set-cookie').split(';')[0];
    assert.equal((await promotedLogin.json()).user.role,'admin');
    const persistedAdminData=await (await fetch(base+'/api/data',{headers:{Cookie:promotedCookie}})).json();
    const promotedAccount=persistedAdminData.accounts.find(a=>a.id===secondUser.id);
    assert.equal(promotedAccount.role,'admin');assert.equal(promotedAccount.promoted_by,'Legacy Admin');assert.ok(promotedAccount.promoted_at);
    assert.ok(existsSync(database));
  } finally {
    if(child&&child.exitCode===null)await stop();
    for(const file of [database,database+'-wal',database+'-shm'])if(existsSync(file))unlinkSync(file);
    rmdirSync(directory);
  }
});
