test('Dentist availability, per-dentist conflicts, admin proposals, responses, and exact unread count',async()=>{
  patient=(await api('/login','POST',{email:'test@example.test',password:'NewPassword123!'})).cookie;
  let date=dateOffset(20);if(new Date(date+'T12:00:00').getDay()===0)date=dateOffset(21);
  let data=(await api('/data','GET',null,patient)).data;
  assert.equal(data.dentists.length,4);
  assert.equal((await api('/dentists/4','PATCH',{available:true},patient)).status,403);
  assert.equal((await api('/appointments','POST',{service_id:1,dentist_id:4,date,time:'09:00'},patient)).status,400);
  const booking=await api('/appointments','POST',{service_id:1,dentist_id:2,date,time:'09:00'},patient);
  assert.equal(booking.status,201);
  // Another patient can see a different dentist at the same time.
  assert.equal((await api('/appointments','POST',{service_id:1,dentist_id:3,date,time:'09:00'},other)).status,201);
  assert.equal((await api('/appointments','POST',{service_id:1,dentist_id:2,date,time:'09:00'},other)).status,409);
  // One patient cannot book two dentists simultaneously.
  assert.equal((await api('/appointments','POST',{service_id:1,dentist_id:1,date,time:'09:00'},patient)).status,409);
  assert.equal((await api(`/slots?date=${date}&dentist=2`,'GET',null,other)).data.slots[0].available,false);
  assert.equal((await api(`/slots?date=${date}&dentist=1`,'GET',null,other)).data.slots[0].available,false);
  assert.equal((await api('/appointments/'+booking.data.id,'PATCH',{propose:true,date,time:'10:00'},patient)).status,400);
  assert.equal((await api('/appointments/'+booking.data.id,'PATCH',{propose:true,date,time:'10:00'},admin)).status,200);
  data=(await api('/data','GET',null,patient)).data;
  const proposal=data.reschedules[0];assert.equal(proposal.actor,'admin');assert.equal(proposal.status,'Pending');
  assert.equal(data.appointments.find(a=>a.id===booking.data.id).time,'09:00','Original booking retained until accepted');
  assert.equal((await api('/reschedules/'+proposal.id,'PATCH',{decision:'accept'},other)).status,404);
  assert.equal((await api('/reschedules/'+proposal.id,'PATCH',{decision:'accept'},patient)).status,200);
  data=(await api('/data','GET',null,patient)).data;
  assert.equal(data.appointments.find(a=>a.id===booking.data.id).time,'10:00');assert.equal(data.reschedules[0].status,'Accepted');
  assert.equal((await api('/reschedules/'+proposal.id,'PATCH',{decision:'accept'},patient)).status,400);
  // A proposed time is checked again at acceptance, including dentist availability.
  assert.equal((await api('/appointments/'+booking.data.id,'PATCH',{propose:true,date,time:'10:30'},admin)).status,200);
  const next=(await api('/data','GET',null,patient)).data.reschedules[0];
  await api('/dentists/2','PATCH',{available:false},admin);
  assert.equal((await api('/reschedules/'+next.id,'PATCH',{decision:'accept'},patient)).status,400);
  await api('/dentists/2','PATCH',{available:true},admin);
  assert.equal((await api('/reschedules/'+next.id,'PATCH',{decision:'decline'},patient)).status,200);
  assert.equal((await api('/data','GET',null,patient)).data.appointments.find(a=>a.id===booking.data.id).time,'10:00');
  // Counterproposal preserves the prior patient request in the change history.
  await api('/appointments/'+booking.data.id,'PATCH',{request:'Reschedule',date,time:'11:00'},patient);
  await api('/appointments/'+booking.data.id,'PATCH',{propose:true,date,time:'11:30'},admin);
  data=(await api('/data','GET',null,patient)).data;
  assert.ok(data.reschedules.some(r=>r.actor==='patient'&&r.status==='Superseded'));
  // Badge count includes unread records beyond the 50 most recent displayed items.
  const {db}=await import('../server/database.js');
  for(let i=0;i<55;i++)db.prepare('INSERT INTO notifications(user_id,message) VALUES (?,?)').run(data.user.id,'Unread count test');
  data=(await api('/data','GET',null,patient)).data;assert.equal(data.notifications.length,50);assert.ok(data.unread_count>50);
  await api('/notifications/read','POST',{},patient);assert.equal((await api('/data','GET',null,patient)).data.unread_count,0);
});
