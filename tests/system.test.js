test('Patient and admin profile pictures validate uploads, stay private, and can be removed independently',async()=>{
  const picture=await sharp({create:{width:80,height:120,channels:3,background:'#2876a5'}}).png().toBuffer();
  const upload=(cookie,buffer=picture,type='image/png')=>fetch(base+'/api/profile/photo',{method:'PUT',headers:{Cookie:cookie,'Content-Type':type},body:buffer});
  assert.equal((await upload('')).status,401);
  assert.equal((await fetch(base+'/api/profile/photo')).status,401);
  assert.equal((await fetch(base+'/api/profile/photo',{headers:{Cookie:other}})).status,404);
  assert.equal((await upload(patient,Buffer.from('not an image'))).status,400);
  assert.equal((await upload(patient,Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"></svg>'),'image/svg+xml')).status,400);
  assert.equal((await upload(patient,Buffer.alloc(2*1024*1024+1))).status,413);
  const result=await upload(patient);assert.equal(result.status,200);
  const saved=(await result.json()).user;assert.ok(saved.photo_url);assert.equal(saved.profile_photo,undefined);
  const response=await fetch(base+saved.photo_url,{headers:{Cookie:patient}});assert.equal(response.status,200);assert.equal(response.headers.get('content-type'),'image/webp');
  const metadata=await sharp(Buffer.from(await response.arrayBuffer())).metadata();assert.equal(metadata.width,512);assert.equal(metadata.height,512);
  assert.equal((await fetch(base+saved.photo_url,{headers:{Cookie:other}})).status,404,'Other accounts cannot retrieve this picture');
  assert.equal((await api('/me','GET',null,other)).data.user.photo_url,null);
  const adminPicture=await sharp({create:{width:40,height:40,channels:3,background:'#389578'}}).jpeg().toBuffer();
  assert.equal((await upload(admin,adminPicture,'image/jpeg')).status,200);
  const adminUrl=(await api('/me','GET',null,admin)).data.user.photo_url;assert.ok(adminUrl);
  const removed=await api('/profile/photo','DELETE',{},patient);assert.equal(removed.status,200);assert.equal(removed.data.user.photo_url,null);
  assert.equal((await fetch(base+'/api/profile/photo',{headers:{Cookie:patient}})).status,404);
  assert.equal((await api('/me','GET',null,admin)).data.user.photo_url,adminUrl);
  await api('/profile/photo','DELETE',{},admin);
});
